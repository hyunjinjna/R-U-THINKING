/**
 * 태그의 설명 문구 하나를 랜덤으로 (문장 반복 방지 원칙)
 * seed를 주면 같은 seed에서는 같은 버전 (한 리포트 안에서 새로고침마다 안 바뀌게)
 * 태그는 원본형("세부사항파악부족")·화면형("세부사항 파악 부족") 어느 쪽이 와도 매칭된다.
 */
const ALIASES = {
  단어뜻을모름: '단어뜻모름',
  비슷한단어혼동: '유사단어혼동',
  품사형태변형이해부족: '품사형태변형부족',
  오류찾기능력부족: '오류찾기부족',
  문장구조이해부족: '문장구조이해부족',
};

export function gapDescription(tag, seed) {
  let clean = String(tag || '').trim().replace(/[\s·]+/g, '');
  if (ALIASES[clean]) clean = ALIASES[clean];
  const list = GAP_DESCRIPTIONS[clean];
  if (!list || list.length === 0) return '';
  let idx;
  if (typeof seed === 'number') idx = Math.abs(seed) % list.length;
  else idx = Math.floor(Math.random() * list.length);
  return list[idx];
}

export { GAP_DESCRIPTIONS };
